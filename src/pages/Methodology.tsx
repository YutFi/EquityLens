import { Page } from '../components/Layout';

export function Methodology() {
  return (
    <Page title="Methodology" subtitle="Exactly what Phase 1 calculates, and what it deliberately does not.">
      <div className="stack">
        <section className="panel">
          <header><h2>Data integrity rules</h2></header>
          <ul className="plain">
            <li>No prices, statements, announcements or news are ever invented. If data is missing, the page says so.</li>
            <li>Estimated or synthetic values are never presented as actual values. Synthetic demo data is labelled on every page it appears.</li>
            <li>Delayed data is never described as real-time. Phase 1 has no real-time data at all.</li>
            <li>Every dataset shows its source, observation date, load time, currency, coverage period, frequency and status.</li>
            <li>Missing information is never treated as poor performance.</li>
          </ul>
        </section>

        <section className="panel">
          <header><h2>Data status labels</h2></header>
          <dl className="kv">
            <dt>Historical</dt><dd>Imported end-of-day history whose latest bar is no more than 7 days old. Not independently verified.</dd>
            <dt>Stale</dt><dd>Latest bar is more than 7 days old.</dd>
            <dt>Incomplete</dt><dd>Rows were rejected on import, or there is a gap of 10+ weekdays (public holidays are not known, so a long holiday period can trigger this).</dd>
            <dt>Synthetic demo</dt><dd>Generated locally for fictional companies. Not market data.</dd>
            <dt>Verified</dt><dd>Reserved for data obtained from an authoritative source and checked by the app. No Phase 1 source qualifies.</dd>
            <dt>Delayed / Estimated / Unavailable</dt><dd>Defined for later phases; Unavailable is used when there is nothing to show.</dd>
          </dl>
        </section>

        <section className="panel">
          <header><h2>Calculations in Phase 1</h2></header>
          <dl className="kv">
            <dt>One-day change %</dt><dd>(Close<sub>t</sub> − Close<sub>t−1</sub>) / Close<sub>t−1</sub> × 100, using each series' two most recent bars.</dd>
            <dt>Comparable set</dt><dd>The dashboard compares only securities whose latest bar is on the most recent date present among loaded companies. Older series are listed as excluded, never mixed in.</dd>
            <dt>Breadth</dt><dd>Counts of comparable securities with a positive, negative or zero one-day change. It describes the loaded set, not the whole exchange.</dd>
            <dt>Volume vs 20-day average</dt><dd>Latest volume ÷ mean volume of the previous 20 bars (needs at least 10 prior bars with volume). "Unusual volume" lists the highest ratios.</dd>
            <dt>Traded value</dt><dd>Close × volume of the latest bar. Used for the heatmap tile area because market cap is unavailable.</dd>
            <dt>20-day volatility</dt><dd>Sample standard deviation of the last 20 daily log returns × √252, shown as a percentage.</dd>
            <dt>Period return</dt><dd>Close on the last trading day on or before (latest date − window) versus the latest close. If the history does not reach back that far, the result is blank instead of extrapolated.</dd>
            <dt>Relative performance</dt><dd>Stock return − benchmark return over the same window.</dd>
            <dt>Maximum drawdown</dt><dd>Largest peak-to-trough decline in closing price over the loaded range.</dd>
            <dt>Weekly / monthly bars</dt><dd>Open of the first day, highest high, lowest low, close of the last day, summed volume; dated on the last trading day. Weeks start on Monday.</dd>
            <dt>Adjusted prices</dt><dd>When every row has an adjusted close, OHLC are scaled by AdjClose/Close. Otherwise prices are shown exactly as supplied and corporate actions are not reflected.</dd>
            <dt>Market status</dt><dd>Compares the exchange-local time with standard session hours. Exchange holidays are not bundled, so this can be wrong on a holiday.</dd>
          </dl>
        </section>

        <section className="panel">
          <header><h2>Market intelligence statements</h2></header>
          <p>Generated by fixed rules from the loaded numbers, each with its evidence. They describe what changed, never why. Price movement and confirmed causes are different things, and no news or event data is loaded in Phase 1.</p>
        </section>

        <section className="panel">
          <header><h2>Not built yet</h2></header>
          <p>Financial statements and ratios, financial-health scoring, valuation (DCF, relative, dividend), technical indicators, forecasting and backtesting, opportunity scanning, company news and announcements, comparison, simulator, watchlist and alerts, and other exchanges. Pages for these are labelled placeholders. When they ship, their formulas will be documented here and in <code>docs/FORMULAS.md</code>.</p>
        </section>
      </div>
    </Page>
  );
}
